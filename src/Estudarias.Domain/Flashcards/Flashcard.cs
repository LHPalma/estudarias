using Estudarias.Domain.Common;
using Estudarias.Domain.Common.Exceptions;

namespace Estudarias.Domain.Flashcards;

public sealed class Flashcard : BaseEntity, IAggregateRoot
{
    public Guid TopicId { get; }
    public string Question { get; }
    public string Answer { get; }
    public FlashcardOrigin Origin { get; }
    public Guid? ErrorTypeId { get; }

    private Flashcard(Guid topicId, string question, string answer, FlashcardOrigin origin, Guid? errorTypeId)
    {
        TopicId = topicId;
        Question = question;
        Answer = answer;
        Origin = origin;
        ErrorTypeId = errorTypeId;
    }

    public static Flashcard CreateManual(Guid topicId, string question, string answer)
    {
        var (validQuestion, validAnswer) = ValidContent(topicId, question, answer);

        return new Flashcard(topicId, validQuestion, validAnswer, FlashcardOrigin.Manual, errorTypeId: null);
    }

    public static Flashcard CreateFromError(Guid topicId, Guid errorTypeId, string question, string answer)
    {
        var (validQuestion, validAnswer) = ValidContent(topicId, question, answer);

        if (errorTypeId == Guid.Empty)
        {
            throw new DomainValidationException(
                FlashcardErrors.ErrorTypeRequired, "A flashcard generated by an error must have an error type.");
        }

        return new Flashcard(topicId, validQuestion, validAnswer, FlashcardOrigin.GeneratedByError, errorTypeId);
    }

    private static (string Question, string Answer) ValidContent(Guid topicId, string question, string answer)
    {
        if (topicId == Guid.Empty)
        {
            throw new DomainValidationException(FlashcardErrors.TopicRequired, "Flashcard topic is required.");
        }

        if (string.IsNullOrWhiteSpace(question))
        {
            throw new DomainValidationException(FlashcardErrors.QuestionRequired, "Flashcard question is required.");
        }

        if (string.IsNullOrWhiteSpace(answer))
        {
            throw new DomainValidationException(FlashcardErrors.AnswerRequired, "Flashcard answer is required.");
        }

        return (question.Trim(), answer.Trim());
    }
}
