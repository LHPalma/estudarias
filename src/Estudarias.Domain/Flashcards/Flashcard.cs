using Estudarias.Domain.Common;
using Estudarias.Domain.Common.Exceptions;

namespace Estudarias.Domain.Flashcards;

public sealed class Flashcard : BaseEntity, IAggregateRoot
{
    public const int CodeMaxLength = ContentCode.MaxLength;

    public Guid TopicId { get; }
    public string Code { get; }
    public string Question { get; private set; }
    public string Answer { get; private set; }
    public FlashcardOrigin Origin { get; private set; }
    public Guid? ErrorTypeId { get; private set; }

    private Flashcard(
        Guid topicId, string code, string question, string answer, FlashcardOrigin origin, Guid? errorTypeId)
    {
        TopicId = topicId;
        Code = code;
        Question = question;
        Answer = answer;
        Origin = origin;
        ErrorTypeId = errorTypeId;
    }

    /// <param name="code">A chave natural do flashcard na carga do conteúdo (formato de <see cref="ContentCode"/>).</param>
    public static Flashcard CreateManual(Guid topicId, string code, string question, string answer)
    {
        var (validCode, validQuestion, validAnswer) = ValidKeyAndContent(topicId, code, question, answer);

        return new Flashcard(topicId, validCode, validQuestion, validAnswer, FlashcardOrigin.Manual, errorTypeId: null);
    }

    /// <param name="code">A chave natural do flashcard na carga do conteúdo (formato de <see cref="ContentCode"/>).</param>
    public static Flashcard CreateFromError(Guid topicId, string code, Guid errorTypeId, string question, string answer)
    {
        var (validCode, validQuestion, validAnswer) = ValidKeyAndContent(topicId, code, question, answer);
        EnsureErrorType(errorTypeId);

        return new Flashcard(topicId, validCode, validQuestion, validAnswer, FlashcardOrigin.GeneratedByError, errorTypeId);
    }

    /// <summary>
    /// Revisa a pergunta, a resposta e a origem, com as regras da criação: com <paramref name="errorTypeId"/> o cartão passa a ser
    /// gerado por aquele tipo de erro; sem, manual. O tópico e o código são a chave natural e não mudam.
    /// </summary>
    public void Revise(string question, string answer, Guid? errorTypeId)
    {
        var (validQuestion, validAnswer) = ValidContent(question, answer);
        if (errorTypeId is { } id)
        {
            EnsureErrorType(id);
        }

        Question = validQuestion;
        Answer = validAnswer;
        Origin = errorTypeId is null ? FlashcardOrigin.Manual : FlashcardOrigin.GeneratedByError;
        ErrorTypeId = errorTypeId;
    }

    private static (string Code, string Question, string Answer) ValidKeyAndContent(
        Guid topicId, string code, string question, string answer)
    {
        if (topicId == Guid.Empty)
        {
            throw new DomainValidationException(FlashcardErrors.TopicRequired, "Flashcard topic is required.");
        }

        if (string.IsNullOrWhiteSpace(code))
        {
            throw new DomainValidationException(FlashcardErrors.CodeRequired, "Flashcard code is required.");
        }

        if (!ContentCode.IsValid(code))
        {
            throw new DomainValidationException(
                FlashcardErrors.CodeInvalid,
                $"Flashcard code must start with a lowercase letter and have lowercase letters and digits separated by single underscores, with at most {CodeMaxLength} characters.");
        }

        var (validQuestion, validAnswer) = ValidContent(question, answer);
        return (code, validQuestion, validAnswer);
    }

    private static (string Question, string Answer) ValidContent(string question, string answer)
    {
        if (string.IsNullOrWhiteSpace(question))
        {
            throw new DomainValidationException(FlashcardErrors.QuestionRequired, "Flashcard question is required.");
        }

        if (string.IsNullOrWhiteSpace(answer))
        {
            throw new DomainValidationException(FlashcardErrors.AnswerRequired, "Flashcard answer is required.");
        }

        return (question.Trim(), answer.Trim());
    }

    private static void EnsureErrorType(Guid errorTypeId)
    {
        if (errorTypeId == Guid.Empty)
        {
            throw new DomainValidationException(
                FlashcardErrors.ErrorTypeRequired, "A flashcard generated by an error must have an error type.");
        }
    }
}
